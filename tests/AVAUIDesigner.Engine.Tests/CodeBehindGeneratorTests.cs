    /// <summary>
    /// With WireEventsInCode the serializer must drop event attributes of named elements; together the
    /// XAML and the C# must wire every handler exactly once.
    /// </summary>
    [Fact]
    public void WireEventsInCode_WithSerializerOmittingNamedEvents_WiresEachHandlerExactlyOnce()
    {
        var doc = Samples.Parse("""
            <Window xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    x:Class="MyApp.Views.MainWindow" Opened="Window_Opened">
                <StackPanel>
                    <Button x:Name="btnOk" Click="BtnOk_Click" />
                    <TextBox x:Name="txtName" TextChanged="TxtName_TextChanged" KeyDown="TxtName_KeyDown" />
                    <Button Click="Unnamed_Click" />
                    <Button x:Name="btnShared" Click="Shared_Click" />
                    <Button Click="Shared_Click" />
                </StackPanel>
            </Window>
            """);
        var xaml = new XamlSerializer { EmitEventAttributesForNamedElements = false }.Serialize(doc);
        var code = Gen.Generate(doc, null, Options(fields: false, wire: true));
        CSharpAssert.ValidAndTidy(code);

        // (element, event, handler) wirings from both sides.
        var wirings = new List<string>();
        var reparsed = Samples.Parse(xaml);
        var index = 0;
        foreach (var e in reparsed.AllElements)
        {
            index++;
            foreach (var h in e.EventHandlers) wirings.Add($"{e.Name ?? "#" + index}.{h.EventName}={h.HandlerName}");
        }
        foreach (Match m in Regex.Matches(code, @"^\s*(\w+)\.(\w+) \+= (\w+);", RegexOptions.Multiline))
        {
            var target = m.Groups[1].Value;
            var element = target == "this" ? reparsed.RootElement : reparsed.NamedElements[target];
            var idx = reparsed.AllElements.ToList().IndexOf(element) + 1;
            wirings.Add($"{element.Name ?? "#" + idx}.{m.Groups[2].Value}={m.Groups[3].Value}");
        }

        var expected = new List<string>();
        index = 0;
        foreach (var e in doc.AllElements)
        {
            index++;
            foreach (var h in e.EventHandlers) expected.Add($"{e.Name ?? "#" + index}.{h.EventName}={h.HandlerName}");
        }

        Assert.Equal(expected.Order(), wirings.Order());
        Assert.Equal(wirings.Count, wirings.Distinct().Count());
        // Named elements are wired in code, root/unnamed in XAML.
        Assert.DoesNotContain("BtnOk_Click", xaml);
        Assert.Contains("Opened=\"Window_Opened\"", xaml);
        Assert.Contains("Click=\"Unnamed_Click\"", xaml);
        // One stub per distinct handler.
        Assert.Single(Regex.Matches(code, @"void Shared_Click\("));
    }

    [Fact]
