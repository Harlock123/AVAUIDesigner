    private const string ExistingUserSource = """
        // My file header
        using System.Diagnostics;
        using Avalonia.Controls;
        using Avalonia.Interactivity;

        namespace MyApp.Views;

        public partial class MainWindow : Window
        {
            private int _counter;

            public MainWindow()
            {
                InitializeComponent();
                WireEvents();
                DataContext = new object();
                Debug.WriteLine("ctor");
            }

            /// <summary>Hand-written helper.</summary>
            public void Helper()
            {
                _counter++;
            }

            private void BtnOk_Click(object? sender, RoutedEventArgs e)
            {
                Debug.WriteLine("ok clicked");
                if (_counter > 2)
                {
                    Close();
                }
            }

            private void OldButton_Click(object? sender, RoutedEventArgs e)
            {
                Debug.WriteLine("legacy");
            }

            private void WireEvents()
            {
                btnOk.Click += BtnOk_Click;
            }
        }
        """;

    [Theory]
    [MemberData(nameof(OptionCombos))]
    public void Merge_PreservesHandlerBodiesUserMembersAndCtorStatements(bool fields, bool wire)
    {
        var code = Gen.Generate(Doc(), ExistingUserSource, Options(fields, wire));
        var root = CSharpAssert.ValidAndTidy(code);

        // Handler body preserved verbatim (statement-wise).
        var click = CSharpAssert.Method(root, "BtnOk_Click");
        Assert.Equal(2, click.Body!.Statements.Count);
        Assert.Equal("Debug.WriteLine(\"ok clicked\");", click.Body.Statements[0].ToString());
        Assert.StartsWith("if (_counter > 2)", click.Body.Statements[1].ToString());
        Assert.Contains("            Close();", code); // re-indented correctly

        // New handler gets a stub.
        Assert.Contains("// TODO: implement", CSharpAssert.Method(root, "TxtName_TextChanged").Body!.ToFullString());

        // Orphaned handler kept, in its region, with body.
        var orphanRegion = code.IndexOf("#region Orphaned Handlers", StringComparison.Ordinal);
        Assert.True(orphanRegion > 0);
        var old = CSharpAssert.Method(root, "OldButton_Click");
        Assert.True(old.SpanStart > orphanRegion);
        Assert.Equal("Debug.WriteLine(\"legacy\");", CSharpAssert.BodyText(old));

        // User members preserved.
        Assert.Contains("private int _counter;", code);
        Assert.Contains("/// <summary>Hand-written helper.</summary>", code);
        Assert.Equal("_counter++;", CSharpAssert.BodyText(CSharpAssert.Method(root, "Helper")));

        // Extra constructor statements preserved after InitializeComponent; no duplicated calls.
        var ctor = root.DescendantNodes().OfType<ConstructorDeclarationSyntax>().Single();
        var stmts = ctor.Body!.Statements.Select(s => s.ToString()).ToList();
        Assert.Equal("InitializeComponent();", stmts[0]);
        Assert.Contains("DataContext = new object();", stmts);
        Assert.Contains("Debug.WriteLine(\"ctor\");", stmts);
        Assert.Equal(1, stmts.Count(s => s == "InitializeComponent();"));
        Assert.Equal(wire ? 1 : 0, stmts.Count(s => s == "WireEvents();"));
        Assert.Equal(wire ? 1 : 0, root.DescendantNodes().OfType<MethodDeclarationSyntax>().Count(m => m.Identifier.Text == "WireEvents"));

        // User's extra usings kept.
        Assert.Contains("using System.Diagnostics;", code);

        // Each method appears once.
        var methodNames = root.DescendantNodes().OfType<MethodDeclarationSyntax>().Select(m => m.Identifier.Text).ToList();
        Assert.Equal(methodNames.Distinct().Count(), methodNames.Count);
    }

