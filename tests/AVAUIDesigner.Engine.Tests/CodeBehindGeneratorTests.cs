public static class CSharpAssert
{
    /// <summary>Parses C# and fails on any syntax error; also checks Scriban whitespace hygiene.</summary>
    public static CompilationUnitSyntax ValidAndTidy(string code)
    {
        var tree = CSharpSyntaxTree.ParseText(code);
        var errors = tree.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        Assert.True(errors.Count == 0, string.Join("\n", errors) + "\n---\n" + code);
        Assert.DoesNotContain("\r", code);
        Assert.False(code.Contains("\n\n\n"), "3+ consecutive newlines:\n" + code);
        var trailing = code.Split('\n').Select((l, i) => (l, i)).Where(x => x.l.Length > 0 && char.IsWhiteSpace(x.l[^1])).ToList();
        Assert.True(trailing.Count == 0, "Trailing whitespace on lines " + string.Join(",", trailing.Select(t => t.i + 1)) + ":\n" + code);
        Assert.EndsWith("}\n", code);
        Assert.False(code.EndsWith("\n\n"), "Ends with blank line");
        return tree.GetCompilationUnitRoot();
    }

    public static MethodDeclarationSyntax Method(CompilationUnitSyntax root, string name) =>
        Assert.Single(root.DescendantNodes().OfType<MethodDeclarationSyntax>(), m => m.Identifier.Text == name);

    public static string BodyText(MethodDeclarationSyntax m) =>
        string.Join("\n", m.Body!.Statements.Select(s => s.ToString()));
}

