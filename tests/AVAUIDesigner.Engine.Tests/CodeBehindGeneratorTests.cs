    [Fact]
    public void Merge_HandlerUnwired_MovesToOrphans_AndBackWhenRewired()
    {
        var doc = Doc();
        var withBody = Gen.Generate(doc, null, Options()).Replace(
            "private void BtnOk_Click(object? sender, RoutedEventArgs e)\n    {\n        // TODO: implement",
            "private void BtnOk_Click(object? sender, RoutedEventArgs e)\n    {\n        Title = \"clicked\";");
        Assert.Contains("Title = \"clicked\";", withBody);

        // Unwire: the handler is orphaned, not deleted.
        doc.NamedElements["btnOk"].SetEventHandler("Click", null);
        var orphaned = Gen.Generate(doc, withBody, Options());
        var root = CSharpAssert.ValidAndTidy(orphaned);
        Assert.True(CSharpAssert.Method(root, "BtnOk_Click").SpanStart > orphaned.IndexOf("#region Orphaned Handlers", StringComparison.Ordinal));
        Assert.Contains("Title = \"clicked\";", orphaned);

        // Re-wire: back in Event Handlers with the body intact, orphan region gone.
        doc.NamedElements["btnOk"].SetEventHandler("Click", "BtnOk_Click");
        var rewired = Gen.Generate(doc, orphaned, Options());
        CSharpAssert.ValidAndTidy(rewired);
        Assert.DoesNotContain("Orphaned", rewired);
        Assert.Contains("        Title = \"clicked\";", rewired);
        Assert.Equal(Gen.Generate(doc, withBody, Options()), rewired);
    }

