    [Theory]
    [MemberData(nameof(OptionCombos))]
    public void AppendixA_Structure(bool fields, bool wire)
    {
        var code = Gen.Generate(Doc(), null, Options(fields, wire));
        var root = CSharpAssert.ValidAndTidy(code);

        var ns = Assert.Single(root.Members.OfType<FileScopedNamespaceDeclarationSyntax>());
        Assert.Equal("MyApp.Views", ns.Name.ToString());
        var cls = Assert.Single(ns.Members.OfType<ClassDeclarationSyntax>());
        Assert.Equal("MainWindow", cls.Identifier.Text);
        Assert.Contains(cls.Modifiers, m => m.IsKind(SyntaxKind.PartialKeyword));
        Assert.Equal("Window", cls.BaseList!.Types.Single().ToString());

        var usings = root.Usings.Select(u => u.Name!.ToString()).ToList();
        Assert.Contains("Avalonia", usings);
        Assert.Contains("Avalonia.Controls", usings);     // TextChangedEventArgs
        Assert.Contains("Avalonia.Interactivity", usings); // RoutedEventArgs
        Assert.Equal(usings.Distinct().Count(), usings.Count);

        var click = CSharpAssert.Method(root, "BtnOk_Click");
        Assert.Equal("RoutedEventArgs", click.ParameterList.Parameters[1].Type!.ToString());
        Assert.Equal("object?", click.ParameterList.Parameters[0].Type!.ToString());
        Assert.Equal("void", click.ReturnType.ToString());
        Assert.Contains(SyntaxKind.PrivateKeyword, click.Modifiers.Select(m => m.Kind()));
        Assert.Contains("// TODO: implement", click.Body!.ToFullString());
        var changed = CSharpAssert.Method(root, "TxtName_TextChanged");
        Assert.Equal("TextChangedEventArgs", changed.ParameterList.Parameters[1].Type!.ToString());

        var ctor = Assert.Single(cls.Members.OfType<ConstructorDeclarationSyntax>());
        Assert.Equal("InitializeComponent()", ctor.Body!.Statements[0].ToString().TrimEnd(';'));

        var fieldNames = cls.Members.OfType<FieldDeclarationSyntax>().SelectMany(f => f.Declaration.Variables).Select(v => v.Identifier.Text).ToList();
        if (fields)
        {
            Assert.Equal(["lblTitle", "txtName", "btnOk"], fieldNames);
            Assert.Contains("private Button btnOk = null!;", code);
            Assert.Contains("#region Designer-generated fields", code);
            Assert.Contains("using Avalonia.Markup.Xaml;", code);
            Assert.Contains("AvaloniaXamlLoader.Load(this);", CSharpAssert.BodyText(CSharpAssert.Method(root, "InitializeComponent")));
        }
        else
        {
            Assert.Empty(fieldNames);
            Assert.DoesNotContain("#region Designer-generated fields", code);
            Assert.DoesNotContain(root.DescendantNodes().OfType<MethodDeclarationSyntax>(), m => m.Identifier.Text == "InitializeComponent");
        }

        var wireEvents = root.DescendantNodes().OfType<MethodDeclarationSyntax>().SingleOrDefault(m => m.Identifier.Text == "WireEvents");
        if (wire)
        {
            Assert.NotNull(wireEvents);
            Assert.Equal("txtName.TextChanged += TxtName_TextChanged;\nbtnOk.Click += BtnOk_Click;", CSharpAssert.BodyText(wireEvents));
            Assert.Contains(ctor.Body.Statements, s => s.ToString() == "WireEvents();");
        }
        else
        {
            Assert.Null(wireEvents);
            Assert.DoesNotContain("WireEvents", code);
        }
    }

