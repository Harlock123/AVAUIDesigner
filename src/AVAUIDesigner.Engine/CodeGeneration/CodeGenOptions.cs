namespace AVAUIDesigner.Engine.CodeGeneration;

public enum CodeBehindStyle
{
    CodeBehind,
    MVVM,
}

public class CodeGenOptions
{
    /// <summary>e.g. "MyApp.Views".</summary>
    public string Namespace { get; set; } = "MyApp.Views";

    /// <summary>e.g. "MainWindow".</summary>
    public string ClassName { get; set; } = "MainWindow";

    /// <summary>e.g. "Window", "UserControl".</summary>
    public string BaseClass { get; set; } = "Window";

    public bool GenerateNullableAnnotations { get; set; } = true;

    /// <summary>
    /// Emit one field per named element plus an InitializeComponent that resolves them. Only use this
    /// when the project disables Avalonia's name generator (&lt;AvaloniaNameGeneratorIsEnabled&gt;false),
    /// otherwise the fields and InitializeComponent are already generated by Avalonia.
    /// </summary>
    public bool GenerateFieldDeclarations { get; set; } = true;

    /// <summary>
    /// Wire named elements' events in a generated WireEvents() method instead of XAML attributes.
    /// The serializer must then omit those attributes (<c>XamlSerializer.EmitEventAttributesForNamedElements</c>)
    /// so that handlers do not run twice.
    /// </summary>
    public bool WireEventsInCode { get; set; }

    public CodeBehindStyle Style { get; set; } = CodeBehindStyle.CodeBehind;

    /// <summary>Namespace for generated ViewModels (defaults to "{root}.ViewModels").</summary>
    public string? ViewModelNamespace { get; set; }

    public string EffectiveViewModelNamespace => ViewModelNamespace ?? DefaultViewModelNamespace(Namespace);

    /// <summary>"MyApp.Views" → "MyApp.ViewModels"; "MyApp" → "MyApp.ViewModels".</summary>
    public static string DefaultViewModelNamespace(string viewNamespace) =>
        viewNamespace.EndsWith(".Views", StringComparison.Ordinal)
            ? viewNamespace[..^".Views".Length] + ".ViewModels"
            : viewNamespace + ".ViewModels";
}
